#!/usr/bin/env python3
"""Turn a plain `pip freeze --all` into a hash-pinned requirements.lock.

    python scripts/hash_lock.py FREEZE.txt > requirements.lock

For every name==version line it collects the sha256 of every file of that exact version from PyPI (JSON API)
and, for the packages PyTorch's cu128 index also serves (torch, torchvision, triton, the nvidia-* CUDA wheels),
from that index too, because its copies are not always byte-identical to PyPI's. Listing every file keeps the
lock usable on other platforms and Python versions; pip accepts any listed hash and refuses a file that matches
none. Standard library only, so it runs before or outside the venv. Needs network access to both indexes.

Install from it with scripts/setup_env.sh (pip --require-hashes --no-deps).
"""
from __future__ import annotations

import json
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

PYPI_JSON = "https://pypi.org/pypi/{name}/{version}/json"
TORCH_INDEX = "https://download.pytorch.org/whl/cu128/{name}/"
LINE = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;]+)$")


def _get(url: str) -> bytes | None:
    for attempt in range(4):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "nt-hash-lock"}), timeout=60) as r:
                return r.read()
        except urllib.error.HTTPError as e:
            if e.code in (403, 404):  # the torch index answers 403 for a project it does not host
                return None
            err = e
        except (urllib.error.URLError, TimeoutError) as e:
            err = e
        time.sleep(2 * (attempt + 1))
    raise RuntimeError(f"{url}: {err}")


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def pypi_hashes(name: str, version: str) -> dict[str, str]:
    raw = _get(PYPI_JSON.format(name=name, version=version))
    if raw is None:
        return {}
    return {f["filename"]: f["digests"]["sha256"] for f in json.loads(raw)["urls"]}


def torch_index_hashes(name: str, version: str) -> dict[str, str]:
    raw = _get(TORCH_INDEX.format(name=normalize(name)))
    if raw is None:
        return {}
    stem = re.sub(r"[-_.]+", "_", name).lower()
    out = {}
    for href in re.findall(r'href="([^"]+)"', raw.decode("utf-8", "replace")):
        path, _, frag = href.partition("#sha256=")
        fname = urllib.parse.unquote(path.rsplit("/", 1)[-1])
        if frag and fname.lower().startswith(f"{stem}-{version.lower()}-"):
            out[fname] = frag
    return out


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    entries = []
    for ln in open(sys.argv[1], encoding="utf-8"):
        ln = ln.strip()
        if not ln or ln.startswith("#"):
            continue
        m = LINE.match(ln)
        if not m:
            raise SystemExit(f"cannot lock {ln!r}: only name==version lines (no editable or local installs)")
        entries.append(m.groups())
    out = ["# Hash-pinned lock of the training environment. Generated by scripts/hash_lock.py from `pip freeze --all`;",
           "# do not edit by hand, rerun `scripts/setup_env.sh --resolve` after changing requirements*.in.",
           "# Install: scripts/setup_env.sh (pip install --require-hashes --no-deps -r requirements.lock)."]
    missing = []
    for name, version in sorted(entries, key=lambda e: normalize(e[0])):
        files = {**pypi_hashes(name, version), **torch_index_hashes(name, version)}
        if not files:
            missing.append(f"{name}=={version}")
            continue
        wheels = [f for f in files if f.endswith(".whl")]
        print(f"{name}=={version}: {len(files)} files ({len(wheels)} wheels)", file=sys.stderr)
        hashes = sorted(set(files.values()))
        out.append(f"{name}=={version} \\")
        out += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    if missing:
        raise SystemExit(f"no files found on PyPI or the torch cu128 index for: {', '.join(missing)}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
